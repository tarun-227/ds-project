"""Summarise playtest evidence into playtest/summary.md.

Run from partB-game/:
    python playtest/analyze.py

Inputs
- playtest/logs/*.csv       written by the game (one file per session)
- playtest/quiz_results.csv filled in by hand after each session
Output
- playtest/summary.md       tables you can paste into REPORT.md
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
LOGS = HERE / "logs"


def load_logs() -> pd.DataFrame:
    files = sorted(LOGS.glob("*.csv"))
    if not files:
        return pd.DataFrame(columns=["timestamp", "session_id", "player", "level", "event", "details"])
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    df["details"] = df["details"].apply(json.loads)
    return df


def gameplay_table(logs: pd.DataFrame) -> pd.DataFrame:
    subs = logs[logs.event == "submit"].copy()
    if subs.empty:
        return pd.DataFrame()
    subs["stars"] = subs.details.apply(lambda d: d.get("stars", 0))
    subs["choice"] = subs.details.apply(lambda d: d.get("degree", d.get("depth")))
    g = subs.groupby(["player", "level"])
    return pd.DataFrame({
        "submissions": g.size(),
        "choices (in order)": g.choice.apply(lambda s: " → ".join(map(str, s))),
        "first stars": g.stars.first(),
        "best stars": g.stars.max(),
    }).reset_index()


def main() -> None:
    logs = load_logs()
    out = ["# Playtest summary (generated by playtest/analyze.py)\n"]

    quiz_path = HERE / "quiz_results.csv"
    quiz = pd.read_csv(quiz_path) if quiz_path.exists() else pd.DataFrame()
    if len(quiz):
        quiz["gain"] = quiz.post_score - quiz.pre_score
        out.append(f"## Pre/post quiz (n = {len(quiz)}, max 5)\n")
        out.append(quiz[["player", "pre_score", "post_score", "gain"]].to_markdown(index=False))
        out.append(f"\n\n**Mean pre {quiz.pre_score.mean():.2f} → post {quiz.post_score.mean():.2f}; "
                   f"mean gain {quiz.gain.mean():+.2f}** "
                   f"({(quiz.gain > 0).sum()} improved, {(quiz.gain == 0).sum()} same, "
                   f"{(quiz.gain < 0).sum()} worse).\n")
        fb = [c for c in ["fun", "clarity", "hints_helpful", "recommend"] if c in quiz]
        out.append("## Feedback (1–5)\n")
        out.append(quiz[fb].agg(["mean", "min", "max"]).round(2).to_markdown())
        out.append("\n\n**Confusing parts mentioned:**\n")
        out += [f"- {p}: {c}" for p, c in zip(quiz.player, quiz.confusing) if isinstance(c, str)]
        out.append("")
    else:
        out.append("_No quiz results yet: fill in playtest/quiz_results.csv._\n")

    gp = gameplay_table(logs)
    if len(gp):
        out.append(f"\n## Gameplay from logs ({logs.session_id.nunique()} sessions)\n")
        out.append(gp.to_markdown(index=False))
        out.append("\n\nReading the choices column: a player who moves from an extreme "
                   "(degree 15, depth 12) towards the middle after the reveal has discovered "
                   "the concept by playing.\n")
        refl = logs[logs.event == "reflection"]
        out.append("\n## Reflections (players' own words)\n")
        out += [f"- **{r.player}** ({r.level}): “{r.details.get('text', '')}”" for r in refl.itertuples()]
        resamples = logs[(logs.event == "resample")].groupby("player").size()
        if len(resamples):
            out.append(f"\n\nLevel 2: players pressed *Draw another sample* "
                       f"{resamples.mean():.1f} times on average before finishing.")
    else:
        out.append("\n_No game logs yet in playtest/logs/._\n")

    (HERE / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {HERE / 'summary.md'}")


if __name__ == "__main__":
    main()
